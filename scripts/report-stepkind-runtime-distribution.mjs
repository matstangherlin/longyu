#!/usr/bin/env node
/**
 * P1-008 — StepKind runtime distribution across mastery passes.
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();
const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-skd-"));

const COGNITIVE = {
  listening: new Set(["listen", "listen_select", "audio_discrimination", "audio_to_action", "dictation"]),
  recognition: new Set(["recognize", "comprehend", "image_choice", "contextual_choice", "odd_one_out"]),
  visual: new Set(["compare_with_image", "image_choice", "place_label"]),
  construction: new Set(["sentence_build", "translation_build", "fill_blank", "hanzi_build", "address_build"]),
  production: new Set(["free_production", "reverse_recall", "produce", "produce_reply"]),
  conversation: new Set(["conversation_scene", "dialogue_choice", "dialogue_completion", "conversation_repair"]),
  transfer: new Set(["transfer_task", "sentence_transform", "substitution_drill"]),
  hanzi: new Set(["hanzi_build", "decompose", "recognize", "hanzi_evolution"]),
  tone: new Set(["tone", "tone_pair"]),
  real_world: new Set([
    "map_direction",
    "sign_reading",
    "menu_reading",
    "price_task",
    "route_sequence",
    "schedule_reading",
    "city_context",
  ]),
};

function familyOf(kind) {
  for (const [family, set] of Object.entries(COGNITIVE)) {
    if (set.has(kind)) return family;
  }
  return "other";
}

try {
  const program = ts.createProgram(
    ["src/features/lesson/lessonTasks.ts", "src/data/journey.ts", "src/data/masteryPilot.ts"],
    {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      skipLibCheck: true,
      strict: false,
      jsx: ts.JsxEmit.ReactJSX,
    }
  );
  if (program.emit().emitSkipped) throw new Error("compile failed");

  const { ALL_LESSONS } = require(path.join(outDir, "src/data/journey.js"));
  const { lessonRoundStepsFor } = require(path.join(outDir, "src/features/lesson/lessonTasks.js"));

  const lines = [
    "# StepKind runtime distribution",
    "",
    "Generated by `npm run report:stepkind-runtime`.",
    "",
    "Simulates plans for the first 30 journey lessons × mastery levels 0–3.",
    "",
  ];

  const global = new Map();
  let consecutiveHanziFails = 0;
  const sampleLessons = ALL_LESSONS.filter((l) => !l.isReview).slice(0, 30);

  for (const lesson of sampleLessons) {
    lines.push(`## ${lesson.id} — ${lesson.title ?? ""}`);
    lines.push("");
    for (const masteryLevel of [0, 1, 2, 3]) {
      const plan = lessonRoundStepsFor(lesson, { masteryLevel, silent: true });
      const counts = new Map();
      for (const step of plan) {
        counts.set(step.kind, (counts.get(step.kind) ?? 0) + 1);
        global.set(step.kind, (global.get(step.kind) ?? 0) + 1);
      }
      for (let i = 1; i < plan.length; i += 1) {
        if (plan[i].kind === "hanzi_build" && plan[i - 1].kind === "hanzi_build") {
          consecutiveHanziFails += 1;
        }
      }
      lines.push(`### Pass ~${masteryLevel + 1} (masteryLevel=${masteryLevel}) — ${plan.length} steps`);
      lines.push("");
      lines.push("| kind | count | % | cognitiveFamily |");
      lines.push("| --- | ---: | ---: | --- |");
      const total = plan.length || 1;
      for (const [kind, count] of [...counts.entries()].sort((a, b) => b[1] - a[1])) {
        lines.push(`| ${kind} | ${count} | ${((count / total) * 100).toFixed(0)}% | ${familyOf(kind)} |`);
      }
      lines.push("");
    }
  }

  lines.push("## Global totals");
  lines.push("");
  lines.push("| kind | count | cognitiveFamily |");
  lines.push("| --- | ---: | --- |");
  for (const [kind, count] of [...global.entries()].sort((a, b) => b[1] - a[1])) {
    lines.push(`| ${kind} | ${count} | ${familyOf(kind)} |`);
  }
  lines.push("");
  lines.push(`Consecutive hanzi_build pairs found: **${consecutiveHanziFails}**`);
  lines.push("");

  const reportPath = path.join(root, "docs/reports/stepkind-runtime-distribution.md");
  await mkdir(path.dirname(reportPath), { recursive: true });
  await writeFile(reportPath, lines.join("\n"), "utf8");
  console.log(`Wrote ${reportPath}`);
  if (consecutiveHanziFails > 0) {
    console.warn(`WARNING: ${consecutiveHanziFails} consecutive hanzi_build pairs`);
  }
} finally {
  await rm(outDir, { recursive: true, force: true });
}
