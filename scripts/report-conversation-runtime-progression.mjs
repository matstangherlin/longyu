#!/usr/bin/env node
/**
 * CONV-028 — Conversation runtime progression across the journey.
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();
const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-crp-"));
const SEED_INTENTS = new Set(["greet", "farewell", "thank", "greet-review", "ask-wellbeing"]);

try {
  const program = ts.createProgram(
    ["src/features/lesson/lessonTasks.ts", "src/data/journey.ts", "src/data/conversationScenes.ts"],
    {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      skipLibCheck: true,
      strict: false,
      jsx: ts.JsxEmit.ReactJSX,
    }
  );
  if (program.emit().emitSkipped) throw new Error("compile failed");

  const { ALL_LESSONS } = require(path.join(outDir, "src/data/journey.js"));
  const { lessonRoundStepsFor } = require(path.join(outDir, "src/features/lesson/lessonTasks.js"));
  const { conversationSceneMainAnswer, conversationSceneById } = require(
    path.join(outDir, "src/data/conversationScenes.js")
  );

  const lines = [
    "# Conversation runtime progression",
    "",
    "Generated by `npm run report:conversation-runtime`.",
    "",
    "| lesson | sceneId | intent | mainAnswer | previousOccurrences | seedIntent |",
    "| --- | --- | --- | --- | ---: | --- |",
  ];

  const seenScene = new Map();
  const seenIntent = new Map();
  const recentIntents = [];
  const recentScenes = [];
  let absurdRepeats = 0;
  let seedStreak = 0;
  let maxSeedStreak = 0;

  const sample = ALL_LESSONS.filter((l) => !l.isReview).slice(0, 40);
  for (const lesson of sample) {
    const plan = lessonRoundStepsFor(lesson, {
      masteryLevel: 0,
      silent: true,
      recentConversationSceneIds: [...recentScenes],
      recentConversationIntentIds: [...recentIntents],
    });
    const scenes = plan.filter((step) => step.kind === "conversation_scene");
    for (const scene of scenes) {
      const sceneId = scene.sceneId ?? "";
      const intent =
        scene.sceneIntent ??
        scene.intent ??
        (sceneId ? conversationSceneById[sceneId]?.intent : undefined) ??
        "";
      const mainAnswer = conversationSceneMainAnswer(scene) ?? "";
      const prev = seenScene.get(sceneId) ?? 0;
      seenScene.set(sceneId, prev + 1);
      seenIntent.set(intent, (seenIntent.get(intent) ?? 0) + 1);
      const isSeed = SEED_INTENTS.has(intent);
      if (isSeed) {
        seedStreak += 1;
        maxSeedStreak = Math.max(maxSeedStreak, seedStreak);
      } else {
        seedStreak = 0;
      }
      if (prev >= 2 && recentScenes.slice(0, 3).includes(sceneId)) absurdRepeats += 1;
      lines.push(
        `| ${lesson.id} | ${sceneId} | ${intent} | ${mainAnswer} | ${prev} | ${isSeed ? "yes" : "no"} |`
      );
      recentScenes.unshift(sceneId);
      recentIntents.unshift(intent);
      if (recentScenes.length > 12) recentScenes.length = 12;
      if (recentIntents.length > 12) recentIntents.length = 12;
    }
  }

  lines.push("");
  lines.push(`Absurd near-repeats (same scene in last 3, already seen ≥2): **${absurdRepeats}**`);
  lines.push(`Max consecutive seed-intent streak: **${maxSeedStreak}**`);
  lines.push("");
  lines.push("## Intent frequencies");
  lines.push("");
  for (const [intent, count] of [...seenIntent.entries()].sort((a, b) => b[1] - a[1])) {
    lines.push(`- ${intent}: ${count}`);
  }
  lines.push("");

  const reportPath = path.join(root, "docs/reports/conversation-runtime-progression.md");
  await mkdir(path.dirname(reportPath), { recursive: true });
  await writeFile(reportPath, lines.join("\n"), "utf8");
  console.log(`Wrote ${reportPath}`);
  if (absurdRepeats > 3 || maxSeedStreak > 4) {
    console.error("Conversation progression HARD FAIL thresholds exceeded");
    process.exitCode = 1;
  }
} finally {
  await rm(outDir, { recursive: true, force: true });
}
