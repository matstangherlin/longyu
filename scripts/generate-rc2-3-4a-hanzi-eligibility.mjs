#!/usr/bin/env node
/** Writes docs/reports/rc2-3-4a-hanzi-eligibility.md from the real eligibility runtime. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { eligibilityAuditRows, loadEligibilityRuntime, runEligibilityGate } from "./lib/hanzi-writing-eligibility.mjs";
import { journeyFingerprint } from "./lib/report-meta.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rt = loadEligibilityRuntime(root);
const gate = runEligibilityGate(rt);
const rows = eligibilityAuditRows(rt);
const verified = rows.filter((r) => r.handwritingReference === "VERIFIED");
const builderOnly = rows.filter((r) => r.builder && r.handwritingReference !== "VERIFIED");
const yes = (b) => (b ? "yes" : "no");

const table = [
  "| CHARACTER | TAUGHT (first introduction) | BUILDER | HANDWRITING_REFERENCE | TRACE | MEMORY | PRODUCTION | FIRST_ELIGIBLE_LOCATION |",
  "|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.character} \`${r.charId}\` | ${r.taught} | ${yes(r.builder)} | ${r.handwritingReference} | ${r.trace} | ${r.memory} | ${r.production} | ${r.firstEligibleLocation} |`),
].join("\n");

const journey = gate.journeyWriting.length
  ? gate.journeyWriting.map((w) => `- \`${w.lessonId}\` M${w.masteryPass}: ${w.character} → ${w.stage} (${w.mode}) — eligible`).join("\n")
  : "- none";

const md = `# RC2.3.4A — Hànzì Pedagogical Eligibility

Generated by \`node scripts/generate-rc2-3-4a-hanzi-eligibility.mjs\` · Journey fingerprint \`${journeyFingerprint(root)}\`.

## Gate

**${gate.failures.length === 0 ? "HANZI_PEDAGOGICAL_ELIGIBILITY_PASS" : "HANZI_PEDAGOGICAL_ELIGIBILITY_FAIL"}** — \`npm run gate:rc2-3-4-hanzi-writing\`
(\`validate:hanzi-writing-eligibility\` + 12 mutations in \`test:hanzi-writing-eligibility\` + geometry + pointer).

${gate.failures.map((f) => `- ${f.code} ${f.subject}: ${f.message}`).join("\n") || "Zero failures on real data."}

## Contract

\`src/lib/hanziWriting/curriculumLeak.ts\` is the single authority (it already wrapped \`hasLearnerBeenTaught\`):

| State | Meaning | Allows |
|---|---|---|
| \`NOT_INTRODUCED\` | No canonical knowledge source says the learner met the character | nothing graded; only a typed, non-graded \`HanziWritingPedagogicalException\` (registry empty) |
| \`INTRODUCED_NO_WRITING_DATA\` | Taught, but no VERIFIED handwriting reference | recognition / assembly per curriculum; writing falls back (\`HANDWRITING_DATA_REQUIRED\`) |
| \`TRACE_ELIGIBLE\` | Taught + VERIFIED reference | TRACE, COMPLETE (missing stroke) |
| \`MEMORY_ELIGIBLE\` | + ≥1 correct trace recorded | MEMORY_WRITE |
| \`PRODUCTION_ELIGIBLE\` | + ≥1 correct memory write recorded | CONTEXT_USE |

"Taught" = any of the existing canonical stores, no new authority:
\`hasLearnerBeenTaught(char:…)\` (Pedagogy V6 map) · \`store.learnedChars\` (SRS) · a completed Journey lesson whose steps put the
character in focus (\`recognize\` / \`decompose\` / \`hanzi_evolution\` / \`hanzi_build\`), derived by \`introductions.ts\`.

Preserved: \`BUILDER_GEOMETRY_NOT_GRADING_SOURCE\` (builder SVG never grades) and \`HANDWRITING_DATA_REQUIRED\` (no inferred stroke order).

## PREMATURE_WRITING_LEAK found in #314 (parent \`9819607\`) and closed here

| Surface | Before (parent) | After |
|---|---|---|
| Hànzì hub → Traçar / Memória (\`HanziTrainingSession.tsx\`) | pool = all 11 verified references; MEMORY graded (\`evaluative\`) for a brand-new learner | pool = \`eligibleWritingCharacters(…)\`; empty pool shows a locked message and does **not** consume a training charge |
| Writing Lab (\`HanziWritingLab.tsx\`) | all 11 selectable, memory mode graded immediately | non-taught characters disabled; memory locked until a correct trace |
| Journey overlay (\`applyWriting.ts\`) | M4 jumped straight to graded MEMORY_WRITE | M4 requires a recorded correct trace, otherwise TRACE (guide 1) |
| \`isCharacterTaught\` | informal allowlist: \`completedLessons.includes("p1-primeiros-hanzi")\` ⇒ 木 / 人 | derived introduction index + learnedChars + taught map; gate fails if a literal allowlist returns |

## Journey runtime writing steps (learner who completed exactly the previous lessons)

${gate.journeyWritingSteps} writing overlays across ${rt.journeyPlans.length} real lesson×pass plans:

${journey}

Most \`hanzi_build\` / \`recognize\` Journey steps carry no \`hanzi\` field, so the overlay rarely attaches in the Journey;
writing practice is reached mainly through the Hànzì hub and the Lab — both now gated.

## Verified references (${verified.length}) — all still functional

${verified.map((r) => `${r.character}`).join(" ")} — each blocked before its introduction lesson, TRACE_ELIGIBLE right after, MEMORY only after a correct trace, PRODUCTION only after a correct memory write (gate G2).

## Builder-supported without verified handwriting (${builderOnly.length})

Always \`INTRODUCED_NO_WRITING_DATA\` once taught; every writing stage refused (gate G3). No stroke data invented.

## Audit table

${table}
`;
fs.writeFileSync(path.join(root, "docs/reports/rc2-3-4a-hanzi-eligibility.md"), md);
console.log(`wrote docs/reports/rc2-3-4a-hanzi-eligibility.md (${rows.length} rows, ${gate.failures.length} failures)`);
