#!/usr/bin/env node
/** Writes docs/reports/rc2-3-5-contrast-library.md (+ .json) from Contrast Library V2. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { require as tsRequire } from "./lib/v495a-runtime.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const L = tsRequire("../../src/lib/audioContrastPairs.ts");
const { PRONUNCIATION_CORE_BR } = tsRequire("../../src/data/pronunciationCoreBr.ts");
const { accepted, rejected } = L.buildContrastLibrary();
const count = (rows, f) => rows.reduce((o, r) => ((o[f(r)] = (o[f(r)] ?? 0) + 1), o), {});
const byKind = count(accepted, (e) => e.kind);
const byFamily = count(accepted, (e) => e.family);
const bySource = {};
for (const e of accepted) for (const s of e.sources) bySource[s] = (bySource[s] ?? 0) + 1;
const curriculum = accepted.filter((e) => e.curriculumBacked).length;
const discovery = accepted.filter((e) => e.discoveryOnly).length;
const toneFamilies = ["1x2", "1x3", "1x4", "2x3", "2x4", "3x4"].map((f) => `| ${f.replace("x", " × ")} | ${byFamily[`tone:${f}`] ?? 0} |`);
const fam = (k) => Object.entries(byFamily).filter(([f]) => f.startsWith(`${k}:`)).map(([f, n]) => `| ${f.slice(k.length + 1)} | ${n} |`);
const labAudio = PRONUNCIATION_CORE_BR.map((c) => `| ${c.id} | ${c.title} | ${c.sounds.map((s) => `${s.hanzi} ${s.pinyin}`).join(" · ")} | ${L.soundsShareCanonicalVoice(c.sounds.map((s) => s.hanzi)) ? "READY (same canonical voice)" : "AUDIO_PENDING — articulation only"} |`);
const rows = accepted.map((e) => `| ${e.kind} | ${e.family.split(":")[1]} | ${e.a.hanzi} ${e.a.pinyin} | ${e.b.hanzi} ${e.b.pinyin} | ${e.sources.join(", ")} | ${e.curriculumBacked ? "yes" : "no"}${e.discoveryOnly ? " (discovery only)" : ""} |`);
const rej = rejected.map((r) => `| ${r.a} | ${r.b} | ${r.reason} | ${r.sources.join(", ")} |`);

const md = `# RC2.3.5 — Canonical Contrast Library V2

Generated by \`node scripts/generate-rc2-3-5-contrast-library.mjs\` from \`src/lib/audioContrastPairs.ts\` (\`buildContrastLibrary\`).

## Totals

| | |
|---|---|
| Accepted contrasts | **${accepted.length}** (tone ${byKind.tone ?? 0} · initial ${byKind.initial ?? 0} · final ${byKind.final ?? 0}) |
| Same canonical voice (\`fixed-speech-xiaoxiao-v1\`) on both sides | **${accepted.length}/${accepted.length}** — enforced, never asserted |
| Curriculum-backed (Journey corpus / taught tone sets) | ${curriculum} |
| Discovery-only (\`contrastOnly\` demo words) | ${discovery} |
| Rejected candidates | ${rejected.length} |
| Sources merged (no fifth source) | ${Object.entries(bySource).map(([s, n]) => `${s} ${n}`).join(" · ")} |

A contrast is accepted only if exactly **one** dimension changes (tone with identical segments, or initial/final with identical tone),
both sides resolve to a canonical asset, and both assets share the canonical speaker.

## By tone

| Pair | Contrasts |
|---|---|
${toneFamilies.join("\n")}

Neutral tone: excluded on purpose — \`buildToneMinimalPairs\` skips tone 5 (the neutral tone is contextual, not a citation-form contrast); no neutral pair was fabricated.

## By initial

| Family | Contrasts |
|---|---|
${fam("initial").join("\n")}

## By final

| Family | Contrasts |
|---|---|
${fam("final").join("\n")}

Missing families (no real same-tone word pair with canonical audio in the corpus): **b × p, d × t, r × l, u × ü, an × ang, en × eng, in × ing, ian × iang**.
They need new fixed-speech assets (\`npm run audio:regenerate-fixed-speech\`, owner credentials) — not invented here.

## Pinyin Lab (Pronunciation Core BR) audio state

| Id | Title | Sounds | Audio |
|---|---|---|---|
${labAudio.join("\n")}

Before RC2.3.5, 13 of the 14 lab comparisons had at least one **silent** side (fixed content never falls back to TTS) and the drill still graded identification — a guess.
Now: g × k, j × q × x, ch × sh and z × c use real same-tone words with canonical audio; the rest stay articulation-only until assets exist.

## Curriculum eligibility (\`contrastEligibility\`)

Reuses the Journey authority for minimal pairs (\`seenGlyphs\`), no new source of truth:
\`NOT_READY\` (no common canonical voice) → \`DISCOVERY_ELIGIBLE\` (unseen side or \`contrastOnly\`; listen, no grade) → \`PERCEPTION_ELIGIBLE\` (both sides seen; identify counts) → \`PRODUCTION_ELIGIBLE\` (+ recorded perception with ≥ 2/3 correct).

## Rejected candidates

| A | B | Reason | Source |
|---|---|---|---|
${rej.join("\n")}

Also fixed at the source: 37 of the 53 Journey segment "minimal pairs" changed tone too (e.g. 是 shì × 西 xī labelled "sh × x").
\`perceptionDrills.ts\` now requires the same tone for initial/final pairs; the two RC2.2.32 seeds that did the same (西 xī × 十 shí, 谢 xiè × 小 xiǎo) are retired in \`SUPERSEDED_CONTRAST_SEEDS\`.

## Full list

| Kind | Family | A | B | Sources | Curriculum |
|---|---|---|---|---|---|
${rows.join("\n")}
`;
fs.writeFileSync(path.join(root, "docs/reports/rc2-3-5-contrast-library.md"), md);
fs.writeFileSync(
  path.join(root, "docs/reports/rc2-3-5-contrast-library.json"),
  JSON.stringify({ id: "rc2-3-5-contrast-library", total: accepted.length, byKind, byFamily, curriculumBacked: curriculum, discoveryOnly: discovery, rejected, accepted: accepted.map((e) => ({ id: e.id, kind: e.kind, family: e.family, a: `${e.a.hanzi}|${e.a.pinyin}|${e.a.audioId}`, b: `${e.b.hanzi}|${e.b.pinyin}|${e.b.audioId}`, sources: e.sources })) }, null, 2) + "\n"
);
console.log(`wrote contrast library report: ${accepted.length} accepted, ${rejected.length} rejected`);
