/**
 * validate:lexical-registry — LEX-032/033/035
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function compile() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-lexreg-"));
  const program = ts.createProgram(
    [
      "src/data/lexicalRegistry.ts",
      "src/data/lexicalGoals.ts",
      "src/data/lexicalLifecycleEntries.ts",
      "src/data/slotPatterns.ts",
      "src/data/chunks.ts",
      "src/data/characters.ts",
    ],
    {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      resolveJsonModule: true,
      skipLibCheck: true,
      strict: false,
    }
  );
  if (program.emit().emitSkipped) {
    await rm(outDir, { recursive: true, force: true });
    throw new Error("compile failed");
  }
  return { outDir, load: (rel) => require(path.join(outDir, rel)) };
}

async function main() {
  const { outDir, load } = await compile();
  try {
    const {
      buildLexicalRegistry,
      metricsFromRegistry,
      mapCommon5000ToAtlas,
      tierHistogram,
    } = load("src/data/lexicalRegistry.js");
    const { JOURNEY_LEXICAL_GOALS } = load("src/data/lexicalGoals.js");
    const units = buildLexicalRegistry();
    const metrics = metricsFromRegistry(units);
    const mapping = mapCommon5000ToAtlas(units);
    const tiers = tierHistogram(units);
    const inAtlas = mapping.filter((r) => r.existsInAtlas).length;
    const topUseful = [...mapping].sort((a, b) => b.usefulness - a.usefulness).slice(0, 40);

    const lines = [
      "# Common 5000 → Atlas mapping",
      "",
      "Generated by `npm run validate:lexical-registry` (LEX-034).",
      "",
      "## Summary",
      "",
      `| Metric | Value |`,
      `| --- | ---: |`,
      `| Corpus characters | ${mapping.length} |`,
      `| Present in Atlas chars | ${inAtlas} |`,
      `| Registry characters | ${metrics.uniqueCharacters} |`,
      `| Registry words | ${metrics.uniqueWords} |`,
      `| Registry chunks | ${metrics.uniqueChunks} |`,
      `| Patterns | ${metrics.patterns} |`,
      `| Productive-tier units | ${metrics.productiveUnits} |`,
      `| Receptive-tier units | ${metrics.receptiveUnits} |`,
      "",
      "## Product goals (LEX-030)",
      "",
      `- Productive target: ${JOURNEY_LEXICAL_GOALS.productiveTargetMin}–${JOURNEY_LEXICAL_GOALS.productiveTargetMax}`,
      `- Receptive target: ${JOURNEY_LEXICAL_GOALS.receptiveTargetMin}–${JOURNEY_LEXICAL_GOALS.receptiveTargetMax}`,
      `- Atlas long-term characters: ${JOURNEY_LEXICAL_GOALS.atlasLongTermCharacters}`,
      "",
      "## Tier histogram",
      "",
    ];
    for (const [label, count] of Object.entries(tiers)) {
      lines.push(`- ${label}: ${count}`);
    }
    lines.push("", "## Top usefulness characters (frequency × utility)", "");
    lines.push("| rank | char | usefulness | chunks | inAtlas |", "| ---: | --- | ---: | --- | --- |");
    for (const row of topUseful) {
      lines.push(
        `| ${row.frequencyRank} | ${row.character} | ${row.usefulness.toFixed(1)} | ${row.chunksUsingCharacter.join(", ") || "—"} | ${row.existsInAtlas ? "yes" : "no"} |`
      );
    }

    const mappingPath = path.join(root, "docs/reports/common-5000-atlas-mapping.md");
    await mkdir(path.dirname(mappingPath), { recursive: true });
    await writeFile(mappingPath, lines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${mappingPath}`);
    console.log(
      `Registry: chars=${metrics.uniqueCharacters} words=${metrics.uniqueWords} chunks=${metrics.uniqueChunks} patterns=${metrics.patterns}`
    );
    console.log(`5000 corpus mapped: ${mapping.length}; in Atlas chars: ${inAtlas}`);

    if (units.length < 200) {
      console.error("FAIL: registry too small");
      process.exitCode = 1;
    }
    if (mapping.length < 4000) {
      console.error("FAIL: common5000 corpus incomplete");
      process.exitCode = 1;
    }
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
