/**
 * validate:productive-vocabulary — LEX-046
 * Produtivo = compreende + recupera + produz + contexto (heurística sobre steps).
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

const COMPREHEND = new Set(["listen", "listen_select", "comprehend", "match_pairs", "flash", "read"]);
const RECALL = new Set(["dialogue_choice", "fill_blank", "listen_select", "match_pairs"]);
const PRODUCE = new Set(["sentence_build", "produce", "translation_build", "write", "fill_blank"]);
const CONTEXT = new Set(["conversation_scene", "dialogue_choice", "read"]);

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-prod-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/journey.ts",
        "src/data/chunks.ts",
        "src/data/atlasCurriculum.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/lexicalProgression.ts",
        "src/features/lesson/lessonTasks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
        jsx: ts.JsxEmit.ReactJSX,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const { ALL_LESSONS } = require(path.join(outDir, "src/data/journey.js"));
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));
    const { LEXICAL_LIFECYCLE } = require(path.join(outDir, "src/data/atlasCurriculum.js"));

    const byHanzi = Object.fromEntries(CHUNKS.map((c) => [c.hanzi.replace(/[？?！!。]/g, ""), c]));
    const stats = new Map();

    const bump = (hanzi, kind, lessonId) => {
      const key = hanzi.replace(/[？?！!。\s]/g, "");
      if (!key || !byHanzi[key]) return;
      const row = stats.get(key) ?? {
        hanzi: key,
        ref: `chunk:${byHanzi[key].id}`,
        comprehend: 0,
        recall: 0,
        produce: 0,
        context: 0,
        lessons: new Set(),
      };
      row[kind] += 1;
      row.lessons.add(lessonId);
      stats.set(key, row);
    };

    for (const lesson of ALL_LESSONS) {
      for (const step of lesson.steps ?? []) {
        const blob = [
          step.correctAnswer,
          step.answer,
          step.hanzi,
          step.text,
          step.audioText,
          ...(step.targetParts ?? []),
          ...(step.target ?? []),
        ]
          .filter(Boolean)
          .join("|");
        for (const chunk of CHUNKS) {
          const bare = chunk.hanzi.replace(/[？?！!。]/g, "");
          if (!bare || bare.length < 2) continue;
          if (!blob.includes(bare) && !blob.includes(chunk.hanzi)) continue;
          if (COMPREHEND.has(step.kind)) bump(bare, "comprehend", lesson.id);
          if (RECALL.has(step.kind)) bump(bare, "recall", lesson.id);
          if (PRODUCE.has(step.kind)) bump(bare, "produce", lesson.id);
          if (CONTEXT.has(step.kind)) bump(bare, "context", lesson.id);
        }
      }
    }

    const rows = [...stats.values()].map((row) => ({
      ...row,
      lessons: [...row.lessons],
      productive:
        row.comprehend >= 1 && row.recall >= 1 && row.produce >= 1 && row.context >= 1,
    }));
    const productive = rows.filter((r) => r.productive);
    const scheduled = LEXICAL_LIFECYCLE.filter((e) => e.role === "productive" || e.role === "core");

    const lines = [
      "# Productive vocabulary",
      "",
      "Generated by `npm run validate:productive-vocabulary` (LEX-046).",
      "",
      "A unit counts as **productive** only with ≥1 comprehend + ≥1 recall + ≥1 produce + ≥1 contextual use (not distractor-only).",
      "",
      `| Metric | Value |`,
      `| --- | ---: |`,
      `| Tracked chunk hits | ${rows.length} |`,
      `| Productive units | ${productive.length} |`,
      `| Lifecycle core/productive roles | ${scheduled.length} |`,
      "",
      "## Productive sample",
      "",
      "| hanzi | ref | C | R | P | Ctx | lessons |",
      "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ];
    for (const row of productive.slice(0, 60)) {
      lines.push(
        `| ${row.hanzi} | ${row.ref} | ${row.comprehend} | ${row.recall} | ${row.produce} | ${row.context} | ${row.lessons.slice(0, 4).join(", ")} |`
      );
    }
    const reportPath = path.join(root, "docs/reports/productive-vocabulary.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${reportPath}`);
    console.log(`Productive units: ${productive.length}`);
    if (productive.length < 15) {
      console.error("FAIL: too few productive units");
      process.exitCode = 1;
    } else console.log("OK productive vocabulary");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
