/**
 * validate:first-50-audit — COMM-027
 * Audits first ~50 acquisition lessons for lexical novelty.
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-f50-"));
  try {
    const program = ts.createProgram(
      ["src/data/journey.ts", "src/data/chunks.ts", "src/data/conversationScenes.ts"],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
        jsx: ts.JsxEmit.ReactJSX,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const { ALL_LESSONS } = require(path.join(outDir, "src/data/journey.js"));
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));
    const { CONVERSATION_SCENES } = require(path.join(outDir, "src/data/conversationScenes.js"));

    const sceneById = Object.fromEntries(CONVERSATION_SCENES.map((s) => [s.sceneId, s]));
    const acquisition = ALL_LESSONS.filter((l) => !l.isReview).slice(0, 50);

    const seenWords = new Set();
    const seenChars = new Set();
    const rows = [];
    for (const lesson of acquisition) {
      const newWords = [];
      const reusedWords = [];
      const newChunks = [];
      const newStructures = [];
      const intents = new Set();

      for (const ch of lesson.newHanzi ?? []) {
        if (!seenChars.has(ch)) {
          seenChars.add(ch);
        }
      }

      const blobParts = [];
      for (const step of lesson.steps ?? []) {
        blobParts.push(
          step.correctAnswer,
          step.answer,
          step.hanzi,
          step.text,
          step.audioText,
          ...(step.targetParts ?? []),
          ...(step.target ?? [])
        );
        if (step.kind === "conversation_scene") {
          const scene = sceneById[step.sceneId];
          if (scene?.intent) intents.add(scene.intent);
        }
        if (step.kind === "sentence_build" && Array.isArray(step.targetParts)) {
          newStructures.push(step.targetParts.join(""));
        }
      }
      const blob = blobParts.filter(Boolean).join("|");
      for (const chunk of CHUNKS) {
        const bare = chunk.hanzi.replace(/[？?！!。\s]/g, "");
        if (!bare || bare.length < 2) continue;
        if (!blob.includes(bare) && !blob.includes(chunk.hanzi)) continue;
        if (seenWords.has(bare)) reusedWords.push(bare);
        else {
          seenWords.add(bare);
          newWords.push(bare);
          newChunks.push(chunk.id);
        }
      }
      rows.push({
        id: lesson.id,
        title: lesson.title,
        newWords,
        newChunks,
        reusedWords: reusedWords.slice(0, 12),
        newStructures: [...new Set(newStructures)].slice(0, 6),
        newConversationIntents: [...intents],
      });
    }

    const stagnant = rows.filter((r) => r.newWords.length === 0 && r.newConversationIntents.length === 0);
    const uniqueTotal = seenWords.size + seenChars.size;
    const lines = [
      "# First 50 acquisition lesson audit",
      "",
      "Generated by `npm run validate:first-50-audit` (COMM-027).",
      "",
      `| Lessons audited | ${rows.length} |`,
      `| Unique multi-char chunks | ${seenWords.size} |`,
      `| Unique newHanzi chars | ${seenChars.size} |`,
      `| Combined unique units | ${uniqueTotal} |`,
      `| Stagnant (no new word/intent) | ${stagnant.length} |`,
      "",
      "| Lesson | newWords | newChunks | reused (sample) | structures | intents |",
      "| --- | --- | --- | --- | --- | --- |",
    ];
    for (const r of rows) {
      lines.push(
        `| ${r.id} | ${r.newWords.slice(0, 8).join("、") || "—"} | ${r.newChunks.slice(0, 6).join(", ") || "—"} | ${r.reusedWords.slice(0, 4).join("、") || "—"} | ${r.newStructures.join(" / ") || "—"} | ${r.newConversationIntents.join(", ") || "—"} |`
      );
    }
    lines.push("");

    const reportPath = path.join(root, "docs/reports/first-50-acquisition-audit.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n"), "utf8");
    console.log(`Wrote ${reportPath}`);
    console.log(
      `Unique chunks=${seenWords.size} chars=${seenChars.size} combined=${uniqueTotal}; stagnant=${stagnant.length}`
    );
    // Labs/perception dilute early sequence; pass on combined lexical units
    if (uniqueTotal < 35 && seenWords.size < 30) {
      console.error(
        `FAIL: expected ≥35 unique units or ≥30 multi-char chunks in first 50, got combined=${uniqueTotal} chunks=${seenWords.size}`
      );
      process.exitCode = 1;
    } else console.log("OK first-50 audit");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
