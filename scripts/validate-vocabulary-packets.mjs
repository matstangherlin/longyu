/**
 * validate:vocabulary-packets — LEX-036/037
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();
const REQUIRED = [
  "family",
  "time",
  "transport",
  "city",
  "health",
  "daily_routine",
  "routine",
  "study",
  "work",
  "restaurant",
  "hotel",
  "airport",
  "payment",
  "directions",
  "weather",
  "social",
  "preferences",
  "emergency",
  "technology",
];

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-packets-"));
  try {
    const program = ts.createProgram(["src/data/vocabularyPacketsV37.ts", "src/data/chunks.ts"], {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      skipLibCheck: true,
      strict: false,
    });
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const { VOCABULARY_PACKETS_V37 } = require(path.join(outDir, "src/data/vocabularyPacketsV37.js"));
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));
    const chunkIds = new Set(CHUNKS.map((c) => `chunk:${c.id}`));
    const byId = Object.fromEntries(VOCABULARY_PACKETS_V37.map((p) => [p.id, p]));
    const errors = [];
    for (const id of REQUIRED) {
      const packet = byId[id];
      if (!packet) {
        errors.push(`missing packet ${id}`);
        continue;
      }
      if (packet.core.length === 0) errors.push(`${id}: core empty`);
      for (const field of ["structures", "questions", "answers", "conversationIntents", "transferScenarios"]) {
        if (!Array.isArray(packet[field])) errors.push(`${id}: missing ${field}`);
      }
      for (const ref of [...packet.core, ...packet.support, ...packet.productive, ...packet.receptive]) {
        if (ref.startsWith("chunk:") && !chunkIds.has(ref)) errors.push(`${id}: unknown ${ref}`);
      }
    }

    const lines = [
      "# Vocabulary packet coverage",
      "",
      "Generated by `npm run validate:vocabulary-packets`.",
      "",
      `| packet | core | support | productive | receptive | structures | intents |`,
      `| --- | ---: | ---: | ---: | ---: | ---: | ---: |`,
    ];
    for (const packet of VOCABULARY_PACKETS_V37) {
      lines.push(
        `| ${packet.id} | ${packet.core.length} | ${packet.support.length} | ${packet.productive.length} | ${packet.receptive.length} | ${packet.structures.length} | ${packet.conversationIntents.length} |`
      );
    }
    const reportPath = path.join(root, "docs/reports/vocabulary-packet-coverage.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${reportPath}`);
    console.log(`Packets: ${VOCABULARY_PACKETS_V37.length}`);
    if (errors.length) {
      for (const e of errors) console.error(e);
      process.exitCode = 1;
    } else console.log("OK vocabulary packets");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
