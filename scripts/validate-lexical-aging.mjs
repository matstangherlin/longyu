/**
 * validate:lexical-aging — LEX-059
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-aging-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/atlasCurriculum.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/journey.ts",
        "src/data/chunks.ts",
        "src/data/lexicalProgression.ts",
        "src/features/lesson/lessonTasks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
        jsx: ts.JsxEmit.ReactJSX,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const { LEXICAL_LIFECYCLE } = require(path.join(outDir, "src/data/atlasCurriculum.js"));
    const { ALL_LESSONS } = require(path.join(outDir, "src/data/journey.js"));
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));

    const lessonIndex = new Map(ALL_LESSONS.map((l, i) => [l.id, i]));
    const uses = new Map();

    for (let i = 0; i < ALL_LESSONS.length; i++) {
      const lesson = ALL_LESSONS[i];
      const refs = new Set([...(lesson.libraryItems ?? []), ...(lesson.reviewItems ?? [])]);
      const blob = JSON.stringify(lesson.steps ?? []);
      for (const chunk of CHUNKS) {
        const ref = `chunk:${chunk.id}`;
        if (refs.has(ref) || blob.includes(chunk.hanzi)) {
          const row = uses.get(ref) ?? { ref, lessons: [] };
          row.lessons.push({ id: lesson.id, index: i });
          uses.set(ref, row);
        }
      }
    }

    const lines = [
      "# Lexical aging",
      "",
      "Generated by `npm run validate:lexical-aging` (LEX-059).",
      "",
      "| ref | introducedAt | lastUsedAt | distanceSinceUse | uses | reinforce planned |",
      "| --- | --- | --- | ---: | ---: | --- |",
    ];
    let stale = 0;
    for (const entry of LEXICAL_LIFECYCLE) {
      const row = uses.get(entry.ref);
      const introducedAt = entry.introduceAt;
      const last = row?.lessons?.[row.lessons.length - 1];
      const introIdx = lessonIndex.get(introducedAt) ?? -1;
      const lastIdx = last?.index ?? introIdx;
      const distance = lastIdx >= 0 ? ALL_LESSONS.length - 1 - lastIdx : 999;
      if (distance > 40 && (row?.lessons.length ?? 0) <= 1) stale += 1;
      lines.push(
        `| ${entry.ref} | ${introducedAt} | ${last?.id ?? "—"} | ${distance} | ${row?.lessons.length ?? 0} | ${(entry.reinforceAt ?? []).join(", ") || "—"} |`
      );
    }
    const reportPath = path.join(root, "docs/reports/lexical-aging.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${reportPath}`);
    console.log(`Lifecycle tracked: ${LEXICAL_LIFECYCLE.length}; potentially stale: ${stale}`);
    // Soft: warn only in V3.7; hard-fail if majority never reused
    if (stale > LEXICAL_LIFECYCLE.length * 0.7) {
      console.error("FAIL: too many lifecycle items appear once and age out");
      process.exitCode = 1;
    } else console.log("OK lexical aging");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
