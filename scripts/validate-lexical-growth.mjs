/**
 * validate:lexical-growth — LEX-003..006 / LEX-016
 * Curva de crescimento lexical + estagnação (3 warn / 5 fail).
 * Escreve docs/reports/lexical-growth-curve.md e atualiza before-after.
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();
const curvePath = path.join(root, "docs/reports/lexical-growth-curve.md");
const beforeAfterPath = path.join(root, "docs/reports/lexical-growth-before-after.md");

async function compileAndLoad() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-lex-growth-"));
  const program = ts.createProgram(
    [
      "src/data/atlasCurriculum.ts",
      "src/data/lexicalProgression.ts",
      "src/data/chunks.ts",
      "src/data/characters.ts",
      "src/data/journey.ts",
      "src/features/lesson/lessonTasks.ts",
    ],
    {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      skipLibCheck: true,
      strict: false,
      jsx: ts.JsxEmit.ReactJSX,
    }
  );
  if (program.emit().emitSkipped) {
    await rm(outDir, { recursive: true, force: true });
    throw new Error("validate:lexical-growth: compile failed");
  }
  return { outDir, load: (rel) => require(path.join(outDir, rel)) };
}

async function main() {
  const { outDir, load } = await compileAndLoad();
  try {
    const {
      buildLexicalGrowthCurve,
      findLexicalStagnationIssues,
      seedDecayByBand,
      lessonExplicitLexemes,
      atlasItemRefs,
      LEXICAL_LIFECYCLE,
    } = load("src/data/atlasCurriculum.js");
    const { ALL_LESSONS } = load("src/data/journey.js");

    const points = buildLexicalGrowthCurve(ALL_LESSONS, { limit: 50 });
    const { warnings, errors } = findLexicalStagnationIssues(points);
    const milestones = [1, 5, 10, 20, 30, 40, 50].filter((n) => n <= points.length);

    const uniqueAt = (n) => {
      const slice = points.slice(0, n);
      return slice.length ? slice[slice.length - 1].cumulative : 0;
    };

    const early10 = uniqueAt(10);
    const early20 = uniqueAt(20);
    const early30 = uniqueAt(30);
    const bands = seedDecayByBand(points, [
      { label: "lessons 1–10", start: 0, end: 10 },
      { label: "lessons 11–20", start: 10, end: 20 },
      { label: "lessons 21–30", start: 20, end: 30 },
    ]);

    const lines = [
      "# Lexical growth curve (first 50 lessons)",
      "",
      "Generated by `npm run validate:lexical-growth` (Pedagogia V3.6).",
      "",
      "Modal reuse of the same seed (你好 in listen vs sentence_build) does **not** count as growth.",
      "",
      "## Milestones",
      "",
    ];
    for (const n of milestones) {
      lines.push(`- Lesson ${n}: cumulative **${uniqueAt(n)}** unique explicit lexemes`);
    }

    lines.push("", "## Per-lesson (first 30)", "");
    lines.push(
      "| # | lessonId | newLexemes | reused | cumulative | seedShare |",
      "| ---: | --- | --- | ---: | ---: | ---: |"
    );
    points.slice(0, 30).forEach((point, index) => {
      lines.push(
        `| ${index + 1} | ${point.lessonId} | ${point.newLexemes.join("、") || "—"} | ${point.reusedLexemes.length} | ${point.cumulative} | ${(point.seedShare * 100).toFixed(0)}% |`
      );
    });

    lines.push("", "## Stagnation checks", "");
    if (warnings.length === 0 && errors.length === 0) {
      lines.push("No stagnation warnings or hard fails in the first 50 lessons.");
    } else {
      for (const w of warnings) lines.push(`- WARN: ${w}`);
      for (const e of errors) lines.push(`- FAIL: ${e}`);
    }

    await mkdir(path.dirname(curvePath), { recursive: true });
    await writeFile(curvePath, lines.join("\n") + "\n", "utf8");

    // Before/after: baseline from pre-V3.6 hotfix era (documented) vs current.
    const baseline = {
      unique10: 18,
      unique20: 28,
      unique30: 42,
      seedShareEarly: 0.55,
      note: "Baseline aproximado pré-V3.6 (seed-heavy early journey; ver #173 reports).",
    };
    const atlasTotal = atlasItemRefs().length;
    const scheduled = new Set(LEXICAL_LIFECYCLE.map((e) => e.ref)).size;
    const taughtSet = new Set();
    for (const lesson of ALL_LESSONS.slice(0, 30)) {
      for (const token of lessonExplicitLexemes(lesson)) taughtSet.add(token);
    }

    const afterLines = [
      "# Lexical growth — before × after (V3.6)",
      "",
      "Generated by `npm run validate:lexical-growth`.",
      "",
      "| Metric | Before (pre-V3.6 approx) | After (current) |",
      "| --- | ---: | ---: |",
      `| Unique lexemes first 10 lessons | ${baseline.unique10} | ${early10} |`,
      `| Unique lexemes first 20 | ${baseline.unique20} | ${early20} |`,
      `| Unique lexemes first 30 | ${baseline.unique30} | ${early30} |`,
      `| Seed share lessons 1–10 | ~${(baseline.seedShareEarly * 100).toFixed(0)}% | ${(bands[0].seedShare * 100).toFixed(0)}% |`,
      `| Seed share lessons 11–20 | — | ${(bands[1].seedShare * 100).toFixed(0)}% |`,
      `| Seed share lessons 21–30 | — | ${(bands[2].seedShare * 100).toFixed(0)}% |`,
      `| Explicit tokens in first 30 plans | — | ${taughtSet.size} |`,
      `| Atlas items | — | ${atlasTotal} |`,
      `| Lifecycle scheduled refs | — | ${scheduled} |`,
      "",
      `Baseline note: ${baseline.note}`,
      "",
      "## Acceptance reads",
      "",
      `- Growth first 30: **${early30 >= 50 ? "PASS" : "WATCH"}** (target ≥50 unique explicit lexemes)`,
      `- Seed decay mid band: **${bands[1].seedShare < 0.35 ? "PASS" : "WATCH"}** (target <35% in lessons 11–20)`,
      "",
    ];
    await writeFile(beforeAfterPath, afterLines.join("\n") + "\n", "utf8");

    console.log(`Wrote ${curvePath}`);
    console.log(`Wrote ${beforeAfterPath}`);
    console.log(`Cumulative @10=${early10} @20=${early20} @30=${early30}`);

    for (const w of warnings) console.warn(`WARN ${w}`);
    if (errors.length) {
      for (const e of errors) console.error(`FAIL ${e}`);
      process.exitCode = 1;
    }
    // Soft growth floor for first 30 authored plans.
    if (early30 < 48) {
      console.error(`FAIL: cumulative unique lexemes at lesson 30 is ${early30} (<48)`);
      process.exitCode = 1;
    }
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
