/**
 * validate:conversation-capabilities + china-survival — COMM-001/019/020/030/031
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

const REQUIRED_CAPABILITY_IDS = [
  "greet",
  "introduce_self",
  "ask_name",
  "say_origin",
  "ask_origin",
  "talk_family",
  "talk_study",
  "talk_work",
  "talk_routine",
  "tell_time",
  "ask_time",
  "order_food",
  "order_drink",
  "ask_price",
  "buy_item",
  "negotiate_basic",
  "pay",
  "ask_location",
  "ask_directions",
  "use_metro",
  "use_train",
  "use_taxi",
  "airport_basic",
  "hotel_checkin",
  "ask_for_help",
  "say_dont_understand",
  "ask_repeat",
  "health_basic",
  "weather_smalltalk",
  "express_preference",
  "make_simple_plan",
];

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-cap-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/conversationCapabilities.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/chunks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const {
      CONVERSATION_CAPABILITIES,
      CHINA_CONVERSATION_BENCHMARK_IDS,
      LONGYU_MINIMAL_CHINA_CONVERSATION,
      CHINA_SURVIVAL_SCENARIOS,
      SIMULATED_CHINA_JOURNEY,
      capabilityCoverage,
    } = require(path.join(outDir, "src/data/conversationCapabilities.js"));
    const { LEXICAL_LIFECYCLE_V37_EXTRA } = require(
      path.join(outDir, "src/data/lexicalLifecycleEntries.js")
    );
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));

    const available = new Set([
      ...CHUNKS.map((c) => `chunk:${c.id}`),
      ...LEXICAL_LIFECYCLE_V37_EXTRA.map((e) => e.ref),
    ]);
    const taughtByLifecycle = new Set(LEXICAL_LIFECYCLE_V37_EXTRA.map((e) => e.ref));
    const coverage = capabilityCoverage(available);
    const errors = [];

    for (const id of REQUIRED_CAPABILITY_IDS) {
      if (!CONVERSATION_CAPABILITIES.some((c) => c.id === id)) {
        errors.push(`missing capability definition: ${id}`);
      }
    }

    const lines = [
      "# Conversation capability map",
      "",
      "Generated by `npm run validate:conversation-capabilities`.",
      "",
      "READY requires vocabulary + question/answer + productive practice + conversation + transfer (COMM-020).",
      "",
      "| Capability | Status | Score | Lex | Struct | Prod | Conv | Transfer | Missing |",
      "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ];
    for (const row of coverage) {
      const s = row.scores;
      lines.push(
        `| ${row.id} | ${row.computedStatus} | ${s.readinessScore.toFixed(2)} | ${s.lexicalCoverage.toFixed(2)} | ${s.structuralCoverage.toFixed(2)} | ${s.productiveCoverage.toFixed(2)} | ${s.conversationCoverage.toFixed(2)} | ${s.transferCoverage.toFixed(2)} | ${row.missingRefs.join(", ") || "—"} |`
      );
    }
    lines.push("", "## Fields per capability", "");
    for (const row of coverage) {
      lines.push(`### ${row.id}`);
      lines.push("");
      lines.push(`- requiredVocabulary: ${row.requiredVocabulary.join(", ") || "—"}`);
      lines.push(`- requiredStructures: ${row.requiredStructures.join("; ") || "—"}`);
      lines.push(`- requiredChunks: ${row.requiredChunks.join(", ")}`);
      lines.push(`- requiredQuestions: ${row.requiredQuestions.join(" / ") || "—"}`);
      lines.push(`- requiredAnswers: ${row.requiredAnswers.join(" / ") || "—"}`);
      lines.push(`- journeyLessons: ${row.journeyLessons.join(", ")}`);
      lines.push(`- productiveCoverage: ${row.hasProductivePractice ? "yes" : "no"}`);
      lines.push(`- conversationCoverage: ${row.hasConversation ? "yes" : "no"}`);
      lines.push(`- status: **${row.computedStatus}**`);
      lines.push("");
    }
    lines.push("## Simulated China Journey", "");
    for (const step of SIMULATED_CHINA_JOURNEY) {
      lines.push(`${step.step}. **${step.scene}** — ${step.capabilityIds.join(", ")}`);
    }
    lines.push("");

    const mapPath = path.join(root, "docs/reports/conversation-capability-map.md");
    await mkdir(path.dirname(mapPath), { recursive: true });
    await writeFile(mapPath, lines.join("\n"), "utf8");

    // China survival benchmark — hard-fail on untaught vocab (COMM-031)
    const survivalLines = [
      "# China survival benchmark",
      "",
      "LONGYU_MINIMAL_CHINA_CONVERSATION (COMM-030/031/032)",
      "",
      "Hard fail if a scenario requires vocabulary not present in Atlas/lifecycle.",
      "",
      "| Scenario | Capabilities | Untaught refs | OK |",
      "| --- | --- | --- | --- |",
    ];
    let survivalFails = 0;
    for (const scenario of CHINA_SURVIVAL_SCENARIOS) {
      const capIds = LONGYU_MINIMAL_CHINA_CONVERSATION[scenario] ?? [];
      const untaught = [];
      for (const id of capIds) {
        const row = coverage.find((c) => c.id === id);
        if (!row) {
          untaught.push(`missing-cap:${id}`);
          continue;
        }
        for (const ref of row.requiredChunks) {
          if (!taughtByLifecycle.has(ref) && !available.has(ref)) untaught.push(ref);
          else if (!available.has(ref)) untaught.push(ref);
        }
      }
      const uniqueUntaught = [...new Set(untaught)];
      const ok = uniqueUntaught.length === 0;
      if (!ok) survivalFails += 1;
      survivalLines.push(
        `| ${scenario} | ${capIds.join(", ")} | ${uniqueUntaught.join(", ") || "—"} | ${ok ? "yes" : "FAIL"} |`
      );
    }
    survivalLines.push(
      "",
      "## Simulated path",
      "",
      "chegar à China → aeroporto → hotel → restaurante → metrô → loja → conhecer alguém → resolver problema simples.",
      "",
      ...SIMULATED_CHINA_JOURNEY.map(
        (s) => `${s.step}. ${s.scene}: ${s.capabilityIds.join(" + ")}`
      ),
      "",
      `Benchmark scenarios clean: **${CHINA_SURVIVAL_SCENARIOS.length - survivalFails}/${CHINA_SURVIVAL_SCENARIOS.length}**`,
      ""
    );

    const survivalPath = path.join(root, "docs/reports/china-survival-benchmark.md");
    await writeFile(survivalPath, survivalLines.join("\n"), "utf8");
    // legacy alias
    await writeFile(
      path.join(root, "docs/reports/china-conversation-benchmark.md"),
      survivalLines.join("\n"),
      "utf8"
    );

    console.log(`Wrote ${mapPath}`);
    console.log(`Wrote ${survivalPath}`);

    for (const id of CHINA_CONVERSATION_BENCHMARK_IDS) {
      if (!CONVERSATION_CAPABILITIES.some((c) => c.id === id)) {
        errors.push(`benchmark capability missing definition: ${id}`);
      }
    }
    if (survivalFails > 0) {
      errors.push(`${survivalFails} China survival scenarios require untaught/missing refs`);
    }

    if (errors.length) {
      for (const e of errors) console.error(`FAIL: ${e}`);
      process.exitCode = 1;
    } else console.log("OK conversation capabilities + china survival");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
