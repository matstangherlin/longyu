/**
 * validate:conversation-capabilities + china benchmark — LEX-050/066
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-cap-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/conversationCapabilities.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/chunks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const {
      CONVERSATION_CAPABILITIES,
      CHINA_CONVERSATION_BENCHMARK_IDS,
      SIMULATED_CHINA_JOURNEY,
      capabilityCoverage,
    } = require(path.join(outDir, "src/data/conversationCapabilities.js"));
    const { LEXICAL_LIFECYCLE_V37_EXTRA } = require(
      path.join(outDir, "src/data/lexicalLifecycleEntries.js")
    );
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));

    const available = new Set([
      ...CHUNKS.map((c) => `chunk:${c.id}`),
      ...LEXICAL_LIFECYCLE_V37_EXTRA.map((e) => e.ref),
    ]);
    const coverage = capabilityCoverage(available);

    const lines = [
      "# Conversation capability map",
      "",
      "Generated by `npm run validate:conversation-capabilities`.",
      "",
      "| Capability | Status | Covered | Missing | Domain | Survival |",
      "| --- | --- | ---: | --- | --- | --- |",
    ];
    for (const row of coverage) {
      lines.push(
        `| ${row.id} | ${row.status} | ${row.coveredRequired}/${row.requiredRefs.length} | ${row.missingRefs.join(", ") || "—"} | ${row.domain} | ${row.survivalChina ? "yes" : "—"} |`
      );
    }
    lines.push("", "## Simulated China Journey", "");
    for (const step of SIMULATED_CHINA_JOURNEY) {
      lines.push(`${step.step}. **${step.scene}** — ${step.capabilityIds.join(", ")}`);
    }

    const mapPath = path.join(root, "docs/reports/conversation-capability-map.md");
    await mkdir(path.dirname(mapPath), { recursive: true });
    await writeFile(mapPath, lines.join("\n") + "\n", "utf8");

    const benchLines = [
      "# China conversation benchmark",
      "",
      "LONGYU_MINIMAL_CHINA_CONVERSATION (LEX-066)",
      "",
      "| Scenario | Capability | Declared status | Refs available |",
      "| --- | --- | --- | --- |",
    ];
    let readyish = 0;
    for (const id of CHINA_CONVERSATION_BENCHMARK_IDS) {
      const row = coverage.find((c) => c.id === id);
      if (!row) {
        benchLines.push(`| ${id} | — | MISSING | no |`);
        continue;
      }
      const ok = row.missingRefs.length === 0;
      if (ok && (row.status === "READY" || row.status === "PARTIAL")) readyish += 1;
      benchLines.push(
        `| ${id} | ${row.labelPt} | ${row.status} | ${ok ? "yes" : "partial (" + row.missingRefs.join(", ") + ")"} |`
      );
    }
    benchLines.push(
      "",
      `Benchmark vocabulary coverage: **${readyish}/${CHINA_CONVERSATION_BENCHMARK_IDS.length}** scenarios have all required refs present in Atlas/lifecycle.`,
      "",
      "Pass rule (V3.7): all required refs exist in Atlas (taught/scheduled may still be PARTIAL).",
      ""
    );
    const benchPath = path.join(root, "docs/reports/china-conversation-benchmark.md");
    await writeFile(benchPath, benchLines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${mapPath}`);
    console.log(`Wrote ${benchPath}`);

    const missingCaps = coverage.filter((c) => c.missingRefs.length > 0 && c.survivalChina);
    if (missingCaps.length) {
      console.warn(
        `WATCH: ${missingCaps.length} survival capabilities still missing some refs: ${missingCaps
          .map((c) => c.id)
          .join(", ")}`
      );
    }
    // Hard fail only if a benchmark capability is completely unknown
    for (const id of CHINA_CONVERSATION_BENCHMARK_IDS) {
      if (!CONVERSATION_CAPABILITIES.some((c) => c.id === id)) {
        console.error(`FAIL: benchmark capability missing definition: ${id}`);
        process.exitCode = 1;
      }
    }
    if (!process.exitCode) console.log("OK conversation capabilities");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
