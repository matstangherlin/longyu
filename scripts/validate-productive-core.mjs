/**
 * validate:productive-core — COMM-004/005/007
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-pcore-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/productiveCore.ts",
        "src/data/slotPatterns.ts",
        "src/data/vocabularyPacketsV37.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/chunks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        skipLibCheck: true,
        strict: false,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const {
      PRODUCTIVE_CORE,
      RECEPTIVE_CORE,
      PRODUCTIVE_CORE_TARGET,
      RECEPTIVE_CORE_TARGET,
      productiveCoreStats,
      buildCombinabilitySnapshot,
      PRODUCTIVE_COMBINATION_BANK,
    } = require(path.join(outDir, "src/data/productiveCore.js"));
    const { CHUNKS } = require(path.join(outDir, "src/data/chunks.js"));
    const { SLOT_PATTERNS } = require(path.join(outDir, "src/data/slotPatterns.js"));

    const chunkIds = new Set(CHUNKS.map((c) => `chunk:${c.id}`));
    const stats = productiveCoreStats();
    const combo = buildCombinabilitySnapshot();
    const errors = [];

    if (!stats.withinProductiveTarget) {
      errors.push(
        `PRODUCTIVE_CORE size ${stats.total} outside ${PRODUCTIVE_CORE_TARGET.min}–${PRODUCTIVE_CORE_TARGET.max}`
      );
    }
    if (!stats.withinReceptiveTarget) {
      errors.push(
        `RECEPTIVE_CORE size ${stats.receptiveTotal} outside ${RECEPTIVE_CORE_TARGET.min}–${RECEPTIVE_CORE_TARGET.max}`
      );
    }
    if (SLOT_PATTERNS.length < 30) errors.push(`Need ≥30 slot patterns, got ${SLOT_PATTERNS.length}`);
    if (combo.possibleUsefulCombinations.length < 150) {
      errors.push(`Need ≥150 possible combinations, got ${combo.possibleUsefulCombinations.length}`);
    }
    if (combo.practicedCombinations.length < 100) {
      errors.push(`Need ≥100 practiced combinations, got ${combo.practicedCombinations.length}`);
    }
    for (const id of PRODUCTIVE_CORE) {
      if (id.startsWith("chunk:") && !chunkIds.has(id)) errors.push(`unknown productive ref ${id}`);
    }

    const lines = [
      "# Productive core",
      "",
      "Generated by `npm run validate:productive-core` (COMM-004/005/007).",
      "",
      "Productive units = words / chunks / patterns (not isolated unused characters).",
      "",
      "| Metric | Value | Target |",
      "| --- | ---: | --- |",
      `| PRODUCTIVE_CORE | ${stats.total} | ${PRODUCTIVE_CORE_TARGET.min}–${PRODUCTIVE_CORE_TARGET.max} |`,
      `| — chunks | ${stats.chunks} | — |`,
      `| — patterns | ${stats.patterns} | — |`,
      `| — combos | ${stats.combos} | — |`,
      `| RECEPTIVE_CORE | ${stats.receptiveTotal} | ${RECEPTIVE_CORE_TARGET.min}–${RECEPTIVE_CORE_TARGET.max} |`,
      `| Slot patterns | ${SLOT_PATTERNS.length} | ≥30 |`,
      `| possibleUsefulCombinations | ${combo.possibleUsefulCombinations.length} | ≥150 |`,
      `| practicedCombinations | ${combo.practicedCombinations.length} | ≥100 |`,
      `| productiveCombinations | ${combo.productiveCombinations.length} | — |`,
      "",
      "## Combinability sample",
      "",
      "| Combination |",
      "| --- |",
      ...PRODUCTIVE_COMBINATION_BANK.slice(0, 24).map((h) => `| ${h} |`),
      "",
      "## Pattern library",
      "",
      "| id | pattern | fills |",
      "| --- | --- | ---: |",
      ...SLOT_PATTERNS.map((p) => `| ${p.id} | ${p.pattern} | ${p.exampleFills.length} |`),
      "",
    ];

    const reportPath = path.join(root, "docs/reports/productive-core.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n"), "utf8");
    // Also keep productive-vocabulary.md pointer for older links
    await writeFile(
      path.join(root, "docs/reports/productive-vocabulary.md"),
      [
        "# Productive vocabulary",
        "",
        "See also `productive-core.md` (COMM-004).",
        "",
        `PRODUCTIVE_CORE: **${stats.total}** · RECEPTIVE_CORE: **${stats.receptiveTotal}**`,
        "",
      ].join("\n"),
      "utf8"
    );

    console.log(`Wrote ${reportPath}`);
    console.log(
      `PRODUCTIVE_CORE=${stats.total} RECEPTIVE_CORE=${stats.receptiveTotal} patterns=${SLOT_PATTERNS.length}`
    );
    if (errors.length) {
      for (const e of errors) console.error(`FAIL: ${e}`);
      process.exitCode = 1;
    } else console.log("OK productive core");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
