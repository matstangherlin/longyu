/**
 * validate:journey-51-100-roadmap — COMM-028
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-r51-"));
  try {
    const program = ts.createProgram(["src/data/lexicalRoadmap.ts"], {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.Node10,
      rootDir: root,
      outDir,
      esModuleInterop: true,
      skipLibCheck: true,
      strict: false,
    });
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const { LESSONS_51_100_ROADMAP, FIRST_50_REBALANCE_NOTES } = require(
      path.join(outDir, "src/data/lexicalRoadmap.js")
    );

    const lines = [
      "# Journey 51–100 lexical roadmap",
      "",
      "Generated by `npm run validate:journey-51-100-roadmap` (COMM-028).",
      "",
      "Plano antecipado — não reescreve todas as lições nesta remessa.",
      "",
      "| Lesson range | Domain / packets | Structures | Capability unlocked | Notes |",
      "| --- | --- | --- | --- | --- |",
    ];
    for (const block of LESSONS_51_100_ROADMAP) {
      lines.push(
        `| ${block.lessonRange} | ${block.focusPackets.join(", ")} | ${block.newStructures.join("; ")} | ${block.conversationGoals.join(", ")} | ${block.notes} |`
      );
    }
    lines.push("", "## Notes from first 50", "");
    for (const note of FIRST_50_REBALANCE_NOTES) lines.push(`- ${note}`);
    lines.push("");

    const reportPath = path.join(root, "docs/reports/journey-51-100-lexical-roadmap.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n"), "utf8");
    console.log(`Wrote ${reportPath}`);
    if (LESSONS_51_100_ROADMAP.length < 5) {
      console.error("FAIL: roadmap needs ≥5 blocks covering 51–100");
      process.exitCode = 1;
    } else console.log("OK journey 51–100 roadmap");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
