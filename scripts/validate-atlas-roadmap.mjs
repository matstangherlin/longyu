/**
 * validate:atlas-roadmap — LEX-054/055 + lifecycle size
 */
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = process.cwd();

async function main() {
  const outDir = await mkdtemp(path.join(os.tmpdir(), "longyu-roadmap-"));
  try {
    const program = ts.createProgram(
      [
        "src/data/atlasCurriculum.ts",
        "src/data/lexicalLifecycleEntries.ts",
        "src/data/lexicalGoals.ts",
        "src/data/lexicalRoadmap.ts",
        "src/data/lexicalRegistry.ts",
        "src/data/chunks.ts",
        "src/data/characters.ts",
        "src/data/slotPatterns.ts",
        "src/data/journey.ts",
        "src/features/lesson/lessonTasks.ts",
      ],
      {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        moduleResolution: ts.ModuleResolutionKind.Node10,
        rootDir: root,
        outDir,
        esModuleInterop: true,
        resolveJsonModule: true,
        skipLibCheck: true,
        strict: false,
        jsx: ts.JsxEmit.ReactJSX,
      }
    );
    if (program.emit().emitSkipped) throw new Error("compile failed");
    const load = (rel) => require(path.join(outDir, rel));
    const { LEXICAL_LIFECYCLE, atlasItemRefs, classifyAtlasItem } = load("src/data/atlasCurriculum.js");
    const { JOURNEY_LEXICAL_GOALS } = load("src/data/lexicalGoals.js");
    const { LESSONS_51_100_ROADMAP, FIRST_50_REBALANCE_NOTES } = load("src/data/lexicalRoadmap.js");
    const { buildLexicalRegistry, mapCommon5000ToAtlas } = load("src/data/lexicalRegistry.js");
    const { ALL_LESSONS } = load("src/data/journey.js");

    const lifecycle = LEXICAL_LIFECYCLE;
    const atlas = atlasItemRefs();
    const units = buildLexicalRegistry();
    const mapping = mapCommon5000ToAtlas(units);
    const classifiedUnits = units.filter((u) => Boolean(u.tier)).length;

    const taught = new Set();
    for (const lesson of ALL_LESSONS) {
      for (const ref of lesson.libraryItems ?? []) taught.add(ref);
    }
    const scheduled = new Set(lifecycle.map((e) => e.ref));
    let taughtN = 0;
    let scheduledN = 0;
    let futureN = 0;
    for (const ref of atlas) {
      const status = classifyAtlasItem(ref, taught, scheduled);
      if (status === "taught") taughtN += 1;
      else if (status === "scheduled") scheduledN += 1;
      else futureN += 1;
    }

    const lines = [
      "# Atlas 5000 roadmap",
      "",
      "Generated by `npm run validate:atlas-roadmap` (LEX-054).",
      "",
      "## Architecture",
      "",
      "```text",
      "CORPUS ~5000 characters",
      "        ↓",
      "ATLAS (chars + words + chunks + structures)",
      "        ↓",
      "CURRICULUM (frequency × usefulness)",
      "        ↓",
      "MASTERY (comprehend → recover → produce)",
      "        ↓",
      "CONVERSATION (multi-item use)",
      "```",
      "",
      "## Targets",
      "",
      `| Version | Classified Atlas units target | Current classified | Lifecycle |`,
      `| --- | ---: | ---: | ---: |`,
      `| V3.7 | ≥${JOURNEY_LEXICAL_GOALS.atlasClassifiedTargets.v37} | **${classifiedUnits}** | ${lifecycle.length} |`,
      `| V3.8 | ≥${JOURNEY_LEXICAL_GOALS.atlasClassifiedTargets.v38} | — | — |`,
      `| V4.x | ≥${JOURNEY_LEXICAL_GOALS.atlasClassifiedTargets.v4x} | — | — |`,
      `| Long term | corpus → ${JOURNEY_LEXICAL_GOALS.atlasLongTermCharacters} chars | corpus rows ${mapping.length} | — |`,
      "",
      "## Current Atlas status",
      "",
      `- Atlas journey refs (chunks+chars authored): ${atlas.length}`,
      `- Taught (journey library/use): ${taughtN}`,
      `- Scheduled (lifecycle): ${scheduledN}`,
      `- Future (authored atlas): ${futureN}`,
      `- Lifecycle entries: **${lifecycle.length}** (min ${JOURNEY_LEXICAL_GOALS.lifecycleMinEntries})`,
      `- Registry-classified units (incl. corpus T5/T6): **${classifiedUnits}**`,
      "",
      "## First 50 rebalance notes",
      "",
      ...FIRST_50_REBALANCE_NOTES.map((n) => `- ${n}`),
      "",
      "## Lessons 51–100 roadmap",
      "",
      `| Range | Packets | Structures | Conversation goals |`,
      `| --- | --- | --- | --- |`,
      ...LESSONS_51_100_ROADMAP.map(
        (b) =>
          `| ${b.lessonRange} | ${b.focusPackets.join(", ")} | ${b.newStructures.join("; ")} | ${b.conversationGoals.join(", ")} |`
      ),
      "",
      "## Important",
      "",
      "- 5.000 characters ≠ 5.000 flashcards.",
      "- Characters enter primarily via useful words/chunks.",
      "- Corpus T6 entries are Atlas reference, not Journey cards.",
      "",
    ];

    const reportPath = path.join(root, "docs/reports/atlas-5000-roadmap.md");
    await mkdir(path.dirname(reportPath), { recursive: true });
    await writeFile(reportPath, lines.join("\n") + "\n", "utf8");
    console.log(`Wrote ${reportPath}`);
    console.log(`Lifecycle entries: ${lifecycle.length}; classified units: ${classifiedUnits}`);

    if (lifecycle.length < JOURNEY_LEXICAL_GOALS.lifecycleMinEntries) {
      console.error(
        `FAIL: lifecycle ${lifecycle.length} < min ${JOURNEY_LEXICAL_GOALS.lifecycleMinEntries}`
      );
      process.exitCode = 1;
    }
    if (classifiedUnits < JOURNEY_LEXICAL_GOALS.atlasClassifiedTargets.v37) {
      console.error(
        `FAIL: classified ${classifiedUnits} < V3.7 target ${JOURNEY_LEXICAL_GOALS.atlasClassifiedTargets.v37}`
      );
      process.exitCode = 1;
    }
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
