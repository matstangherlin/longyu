type DeepStringTree<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringTree<T[K]>;
};

/** Same keys as pt-BR; values may differ per locale. */
export type MessageCatalog = DeepStringTree<typeof ptBR>;

